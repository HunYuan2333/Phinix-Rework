#!/usr/bin/env python3
"""Read-only lexical inventory, not a C# compiler or a correctness verdict.

Run from any directory. Outputs only audit artifacts beside this script.
Comments and string contents are masked before keyword/brace matching.
Conditional compilation branches are all included, not build-resolved.
"""
import collections
import hashlib
import json
import pathlib
import re

OUT = pathlib.Path(__file__).resolve().parent
ROOT = OUT.parents[3]


def mask(source):
    pattern = r'//[^\n]*|/\*[\s\S]*?\*/|@"(?:""|[^"])*"|"(?:\\.|[^"\\])*"|\x27(?:\\.|[^\x27\\])*\x27'
    return re.sub(pattern, lambda m: ''.join('\n' if c == '\n' else ' ' for c in m[0]), source)


def group(path):
    p = path.as_posix()
    if p.startswith('Dependencies/'):
        return 'Shared.Common (client reachability requires review)'
    if '/Tools/' in p or '/Samples/' in p:
        return 'Tools/Samples (supplemental)'
    if p.startswith('Extensions/'):
        return '/'.join(path.parts[:2])
    return 'Host/' + path.parts[1]


records, files = [], []
for top in ('Client', 'Extensions', 'Dependencies/Phinix.Common/Common'):
    for path in sorted((ROOT / top).rglob('*.cs')):
        rel = path.relative_to(ROOT)
        if any(p.lower() in ('bin', 'obj', 'proto', 'compiled') for p in rel.parts):
            continue
        source = path.read_text(encoding='utf-8-sig')
        if '<auto-generated' in source[:1000].lower():
            continue
        clean = mask(source)
        files.append({'path': str(rel), 'group': group(rel), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
        for match in re.finditer(r'\b(catch|throw)\b', clean):
            kind = match[0]
            start = match.start()
            end = start
            if kind == 'catch':
                opening = clean.find('{', match.end())
                if opening < 0:
                    continue
                depth, end = 1, opening + 1
                while end < len(clean) and depth:
                    depth += (clean[end] == '{') - (clean[end] == '}')
                    end += 1
            else:
                semi = clean.find(';', match.end())
                end = semi + 1 if semi >= 0 else source.find('\n', start)
            text = source[start:end]
            flags = []
            if kind == 'catch':
                if re.search(r'\bthrow\s*;', mask(text)):
                    flags.append('bare-rethrow-present; cleanup-may-still-mask-primary')
                if re.search(r'\bthrow\s+(?!new\b)[A-Za-z_]\w*\s*;', mask(text)):
                    flags.append('named-throw-present; inspect-stack-reset')
                if '.Message' in text or '.GetType()' in text:
                    flags.append('lossy-summary-candidate; inspect-downstream')
                if not re.search(r'\bthrow\b', mask(text)):
                    flags.append('consumes-exception; inspect-result-reporting')
            elif re.match(r'throw\s+[A-Za-z_]\w*\s*;', text):
                flags.append('named-throw; inspect-stack-reset')
            records.append({'path': str(rel), 'group': group(rel), 'kind': kind,
                            'line': source.count('\n', 0, start) + 1,
                            'end_line': source.count('\n', 0, end) + 1,
                            'review_hints': flags, 'source': text})

counts = collections.defaultdict(collections.Counter)
for f in files:
    counts[f['group']]['files'] += 1
for r in records:
    counts[r['group']][r['kind']] += 1
summary = {k: dict(v) for k, v in sorted(counts.items())}
(OUT / 'source-inventory.json').write_text(json.dumps({'method': __doc__, 'summary': summary, 'files': files, 'sites': records}, ensure_ascii=False, indent=2) + '\n')
(OUT / 'source-inventory.tsv').write_text('group\tpath\tline\tkind\treview_hints\n' + ''.join(
    f"{r['group']}\t{r['path']}\t{r['line']}\t{r['kind']}\t{'; '.join(r['review_hints'])}\n" for r in records))
print(json.dumps(summary, ensure_ascii=False, indent=2))
print('TOTAL', len(files), 'files;', collections.Counter(r['kind'] for r in records))
